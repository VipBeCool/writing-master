/**
 * 盲盒出题的“多维结构性随机矩阵”（按【学段 × 体裁】全景覆盖）
 *
 * 设计原理：
 * 1. 为什么不能完全不给方向？
 *    本地小参数模型（2B~7B）存在明显的“高频路径依赖（模式坍缩）”：如果只让它“出一道五年级写人题”，
 *    它会高度集中在最高概率的 1~2 个套路（如反复出《我的妈妈》《我的同桌》）。
 * 2. 为什么不能写死固定题库？
 *    写死具体题目会导致抽几次就见底。
 * 3. 最佳实践（全景维度矩阵 + AI 自主发散）：
 *    代码层按【4 大学段 × 12 种体裁】提供覆盖家庭、校园、社区、自然、社会、成长心理、文化思辨的
 *    180+ 个细分切入角度与多样化标题句式，每次随机抽取且近 8 次绝不重复同一角度；
 *    再由 AI 在该维度下结合本年级学生认知自主发散出鲜活具体的题目。
 */
