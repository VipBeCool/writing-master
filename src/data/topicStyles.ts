export function pickLengthStyle(genre?: string, rand: () => number = Math.random): LengthStyle {
  const list = (genre && GENRE_LENGTH_STYLES[genre]) || DEFAULT_LENGTH_STYLES;
  const total = list.reduce((s, x) => s + x.weight, 0);
  let r = rand() * total;
  for (const s of list) {
    r -= s.weight;
    if (r <= 0) return s;
  }
  return list[0];
}

