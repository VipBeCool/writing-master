/** 记录最近抽过的切入角度（队列长度为 8），确保连续点击不会重复同一个切入方向 */
const recentAngles: string[] = [];

export function pickAngle(genre: string, stage?: Stage, lastAngle = ''): string {
  const entry = GENRE_ANGLE_MATRIX[genre] ?? GENRE_ANGLE_MATRIX['记事'];
  const stageSpecific = (stage && entry.byStage?.[stage]) || [];
  // 将学段专属角度与该体裁通用全景角度合并
  const fullPool = [...stageSpecific, ...entry.common];

  const avoidSet = new Set([...recentAngles, lastAngle].filter(Boolean));
  const candidates = fullPool.filter((x) => !avoidSet.has(x));
  const pool = candidates.length > 0 ? candidates : fullPool.filter((x) => x !== lastAngle);
  const chosen = (pool.length > 0 ? pool : fullPool)[Math.floor(Math.random() * (pool.length || fullPool.length))];

  recentAngles.push(chosen);
  if (recentAngles.length > 8) recentAngles.shift();
  return chosen;
}
